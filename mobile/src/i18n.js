const I18nContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState('en');
  const [ready, setReady] = useState(false);

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((saved) => {
        if (LANGUAGES.some((l) => l.code === saved)) setLangState(saved);
      })
      .finally(() => setReady(true));
  }, []);

  function setLang(next) {
    if (!LANGUAGES.some((l) => l.code === next)) return;
    setLangState(next);
    AsyncStorage.setItem(STORAGE_KEY, next).catch(() => {});
  }

  const langInfo = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];
  const isRTL = langInfo.rtl;
  const locale = langInfo.locale;

  function t(key, vars) {
    let str = translations[lang]?.[key] ?? translations.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, String(v));
    }
    return str;
  }

  const n = (value) => Number(value ?? 0).toLocaleString(locale);
  const money = (value) => `${n(value)} ${t('toman')}`;
  const date = (value) => (value ? new Date(value).toLocaleString(locale) : '');
  const dateShort = (value) => (value ? new Date(value).toLocaleDateString(locale) : '');

  if (!ready) return null;

  return (
    <I18nContext.Provider value={{ lang, setLang, isRTL, t, n, money, date, dateShort, languages: LANGUAGES }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within LanguageProvider');
  return ctx;
}
